#!/usr/bin/env python3
"""Measure the WAF's false-positive rate from its own NDJSON logs.

    fpr-analyse.py ACCESS_LOG WAF_LOG [--client-net 10.212.134.] [--json]

WHY THIS EXISTS, AND WHY IT IS PARANOID ABOUT ITS OWN DENOMINATOR

A false-positive rate is a ratio, and this project has twice produced a
meaningless one by not looking at what was in the denominator:

  * keepalived's health check issues a real request every 2s to each node, which
    manufactures ~86k requests/day with no user present. A report once read
    "0.1824% - under the 1% gate" when 364 of 373 requests were that probe and
    the numerator was four of my own test attacks.
  * a rehearsal on the standalone VM reported 16.67% off six self-generated
    requests.

So this tool does not accept a log and print a percentage. It first decides
which requests are REAL, says how it decided, and refuses to report a rate it
cannot stand behind. A rate whose denominator you generated yourself is not a
measurement.

WHAT IT SEPARATES, AND WHY THE DISTINCTION MATTERS

  (1) a rule FIRED          - waf.log carries a line for ANY rule match, and a
                              match well under the site's anomaly threshold
                              changes nothing about the request. Counting these
                              as false positives inflates the rate by orders of
                              magnitude: on real traffic here it read 87.87%
                              while the true would-block rate was 0.0095%.
  (2) the WAF BLOCKED it    - what a user actually experienced.
  (3) the WAF WOULD have    - learning mode's would_block. THIS is the number
      blocked it              that answers "what happens if I enforce?", and it
                              is the only one the go/no-go gate should use.

TRIAGE

Per rule it reports the spread across client IPs and paths. That is the
discriminator: a rule firing across many IPs AND many paths is systematic, i.e.
a false positive; a rule concentrated on one IP or one path is more likely a
real attack. Spread is evidence; a rule name is not.

CONTAMINATION DETECTION

It flags the two shapes that have polluted this project's data before: source
addresses that cannot route to the host (a load generator spoofing
X-Forwarded-For), and near-uniform per-path request counts (a scripted sweep
rather than a human). Both are reported rather than silently filtered, because
the operator has to know the sample was mixed.
"""

import argparse
import collections
import ipaddress
import json
import sys

# User agents that mean "this request was generated by us or by a tool".
#
# `pilotcheck` is the important one and the least obvious. The pilot's own
# start-up verification sends a live SQLi that must return 200 to prove learning
# mode is really in effect — and it wears a browser-shaped UA, from whichever
# address the operator ran it from. That is a synthetic attack sitting inside
# the window, seconds after it opens, indistinguishable by address or UA shape
# from a teammate's browser. Found on 2026-08-30: it was the ONLY "real browser"
# would-block in the window, i.e. it would have been reported as a false
# positive against the WAF on traffic no human ever sent.
#
# The verifier must not be counted by the thing it verifies.
TOOL_UA = (
    "curl", "wget", "python-requests", "python-urllib", "go-http-client",
    "vegeta", "k6", "ab/", "siege", "locust", "sqlmap", "nikto", "nmap",
    "gotestwaf", "postman", "insomnia", "httpie", "pilotcheck",
)
# The docker bridge gateway: a request from here was made ON the box.
LOCAL_HINTS = ("172.17.0.1", "172.18.0.1", "127.0.0.1", "::1")


def load(path):
    rows = []
    try:
        fh = open(path, errors="replace")
    except OSError as e:
        sys.exit(f"cannot read {path}: {e}")
    with fh:
        for line in fh:
            line = line.strip()
            if not line.startswith("{"):
                continue
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return rows


def is_tool(ua):
    ua = (ua or "").lower()
    return any(t in ua for t in TOOL_UA)


def classify(rows, client_net):
    """Split rows into real / tool / local / off-net, and say why."""
    buckets = collections.defaultdict(list)
    for d in rows:
        ip = d.get("ip") or ""
        ua = d.get("ua") or ""
        if ip in LOCAL_HINTS:
            buckets["local"].append(d)
        elif is_tool(ua):
            buckets["tool"].append(d)
        elif client_net and not ip.startswith(client_net):
            buckets["offnet"].append(d)
        elif "Mozilla" not in ua:
            buckets["no_browser_ua"].append(d)
        else:
            buckets["real"].append(d)
    return buckets


def routable_to_private_host(ip):
    """A public source address cannot reach an internal host directly; seeing
    one means something set X-Forwarded-For, i.e. a test harness."""
    try:
        a = ipaddress.ip_address(ip)
    except ValueError:
        return True
    return a.is_private or a.is_loopback


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("access_log")
    ap.add_argument("waf_log")
    ap.add_argument("--client-net", default="",
                    help="restrict the denominator to this address prefix, "
                         "e.g. 10.212.134. — strongly recommended")
    ap.add_argument("--gate", type=float, default=1.0,
                    help="would-block %% considered a pass (default 1.0)")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    acc = classify(load(args.access_log), args.client_net)
    waf_rows = load(args.waf_log)
    real_keys = {(d.get("request_id") or "") for d in acc["real"]}

    denom = len(acc["real"])
    total = sum(len(v) for v in acc.values())

    # Match waf.log lines to the real subset by request_id where available,
    # falling back to the same classification rules.
    def waf_is_real(d):
        rid = d.get("request_id") or ""
        if rid and real_keys:
            return rid in real_keys
        ip, ua = d.get("ip") or "", d.get("ua") or ""
        if ip in LOCAL_HINTS or is_tool(ua):
            return False
        if args.client_net and not ip.startswith(args.client_net):
            return False
        return "Mozilla" in ua

    fired = blocked = would = 0
    by_rule = collections.defaultdict(
        lambda: {"n": 0, "ips": set(), "paths": set(), "enforced": 0})
    for d in waf_rows:
        if not waf_is_real(d):
            continue
        fired += 1
        acted = d.get("action") == "BLOCK"
        wb = bool(d.get("would_block"))
        if acted:
            blocked += 1
        if wb:
            would += 1
        if acted or wb:
            r = by_rule[d.get("rule") or "-"]
            r["n"] += 1
            r["ips"].add(d.get("ip"))
            r["paths"].add(d.get("path"))
            if acted:
                r["enforced"] += 1

    paths = collections.Counter(d.get("path") for d in acc["real"])
    ips = collections.Counter(d.get("ip") for d in acc["real"])
    uas = collections.Counter((d.get("ua") or "")[:48] for d in acc["real"])

    # --- contamination signals -------------------------------------------------
    warnings = []
    if denom == 0:
        warnings.append("no real requests identified — nothing can be measured")
    else:
        if denom < 0.5 * total:
            warnings.append(
                f"only {denom} of {total} requests are real "
                f"({100.0*denom/total:.0f}%) — the rest is tooling or off-net")
        public = [ip for ip in ips if not routable_to_private_host(ip)]
        if public:
            warnings.append(
                f"{len(public)} source addresses are PUBLIC and cannot route to "
                f"an internal host — a harness is setting X-Forwarded-For")
        if paths:
            top = paths.most_common(1)[0]
            if top[1] > 0.5 * denom:
                warnings.append(
                    f"{100.0*top[1]/denom:.0f}% of requests hit a single path "
                    f"({top[0]}) — the app surface exercised is narrow")
            counts = sorted(paths.values(), reverse=True)[:10]
            if len(counts) >= 5 and counts[0] and (counts[4] / counts[0]) > 0.8:
                warnings.append(
                    "top path counts are near-uniform — looks scripted, not human")
        if len(uas) == 1 and denom > 100:
            warnings.append("every request shares one user-agent — likely one client")

    wb_rate = (100.0 * would / denom) if denom else 0.0
    en_rate = (100.0 * blocked / denom) if denom else 0.0

    if args.json:
        print(json.dumps({
            "denominator": denom, "total_seen": total,
            "distinct_ips": len(ips), "distinct_paths": len(paths),
            "rule_fired": fired, "blocked": blocked, "would_block": would,
            "would_block_pct": round(wb_rate, 4),
            "blocked_pct": round(en_rate, 4),
            "warnings": warnings,
            "rules": {k: {"hits": v["n"], "uniq_ip": len(v["ips"]),
                          "uniq_path": len(v["paths"]), "enforced": v["enforced"]}
                      for k, v in by_rule.items()},
        }, indent=2))
        return 0

    print("REAL-TRAFFIC FALSE-POSITIVE MEASUREMENT")
    print("=" * 76)
    print(f"  requests seen                {total}")
    print(f"  of those, judged REAL        {denom}   <- the denominator")
    for k, label in (("tool", "tooling/self-generated"), ("local", "from the host itself"),
                     ("offnet", "outside --client-net"), ("no_browser_ua", "no browser UA")):
        if acc[k]:
            print(f"    excluded: {label:<24} {len(acc[k])}")
    print(f"  distinct client IPs          {len(ips)}")
    print(f"  distinct paths               {len(paths)}"
          f"   ({sum(1 for c in paths.values() if c == 1)} hit exactly once)")
    print(f"  distinct user agents         {len(uas)}")
    print()
    print("  (1) a rule fired (any score, may be far below threshold)")
    print(f"        {fired:>8}   {100.0*fired/denom if denom else 0:.3f}%")
    print("  (2) the WAF BLOCKED it")
    print(f"        {blocked:>8}   {en_rate:.4f}%")
    print("  (3) the WAF WOULD have blocked it   <-- THE FPR NUMBER")
    print(f"        {would:>8}   {wb_rate:.4f}%")
    print()
    print("  rules that blocked or would have blocked:")
    if not by_rule:
        print("    (none)")
    for r, v in sorted(by_rule.items(), key=lambda kv: -kv[1]["n"]):
        systematic = len(v["ips"]) >= 3 and len(v["paths"]) >= 5
        verdict = "SYSTEMATIC -> false positive" if systematic else "concentrated -> inspect"
        print(f"    {r:<11} hits={v['n']:<6} uniq_ip={len(v['ips']):<4} "
              f"uniq_path={len(v['paths']):<4} {verdict}")
    print()

    if warnings:
        print("  ** THE SAMPLE HAS PROBLEMS — read these before believing the rate **")
        for w in warnings:
            print(f"    - {w}")
        print()
        print(f"  VERDICT: NOT A PASS — the gate cannot be judged from this sample.")
        print(f"           (would-block rate was {wb_rate:.4f}%, gate is {args.gate}%)")
        return 2

    if wb_rate <= args.gate:
        print(f"  VERDICT: PASS — {wb_rate:.4f}% would-block, under the {args.gate}% gate.")
        return 0
    print(f"  VERDICT: FAIL — {wb_rate:.4f}% would-block, over the {args.gate}% gate.")
    print("           Triage the systematic rules above and add exclusions.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
